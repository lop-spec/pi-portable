// Isolated real-SDK acceptance: reload an active session without aborting its tool/model run.
// No network, live session mutation, or provider calls.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const host=process.env.PI_TEST_HOST, candidate=process.env.PI_ASYNC_TEST_DIR;
assert.ok(host && candidate);
const require=createRequire(path.join(host,'package.json'));
const {createJiti}=require('jiti');
const aiRoot=path.join(host,'node_modules/@earendil-works/pi-ai/dist');
const sdk=await import(pathToFileURL(path.join(host,'dist/index.js')));
const ai=await import(pathToFileURL(path.join(aiRoot,'compat.js')));
const {AssistantMessageEventStream}=await import(pathToFileURL(path.join(aiRoot,'utils/event-stream.js')));
const jiti=createJiti(import.meta.url,{moduleCache:false,fsCache:false,alias:{'@earendil-works/pi-coding-agent':path.join(host,'dist/index.js'),'@earendil-works/pi-ai':path.join(aiRoot,'compat.js')}});
const mod=await jiti.import(path.join(candidate,'index.ts'));
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'pi-reload-fixture-'));
const originalFetch=globalThis.fetch;
globalThis.fetch=()=>{throw Error('Offline reload acceptance attempted network');};
let releaseTool, toolEntered;
const gate=new Promise(r=>{releaseTool=r;});
const entered=new Promise(r=>{toolEntered=r;});
const logs=[];
let activeConfig={...mod.readConfig(''),startTokens:128000};
let toolSignal, mainCalls=0, summaries=0, session;
try {
 const runtime=await sdk.ModelRuntime.create({authPath:path.join(temp,'auth.json'),modelsPath:null,refreshOnCreate:false});
 await runtime.setRuntimeApiKey('openai','offline-key');
 const model={...ai.getModel('openai','gpt-5'),contextWindow:1050000,maxTokens:8192};
 const native={enabled:true,reserveTokens:144000,keepRecentTokens:20000};
 const settingsManager=sdk.SettingsManager.inMemory({compaction:native,retry:{enabled:false},defaultThinkingLevel:'high'});
 const sessionManager=sdk.SessionManager.create(temp,path.join(temp,'sessions'));
 const loader=new sdk.DefaultResourceLoader({cwd:temp,agentDir:temp,settingsManager,noExtensions:true,noSkills:true,noThemes:true,noPromptTemplates:true,noContextFiles:true,extensionFactories:[pi=>mod.install(pi,{config:activeConfig,log:e=>logs.push(e),settings:()=>native,build:async()=>{summaries++;throw Error('Unexpected summary below threshold');}})],systemPromptOverride:()=> 'Offline reload fixture.'});
 await loader.reload();
 ({session}=await sdk.createAgentSession({cwd:temp,agentDir:temp,resourceLoader:loader,modelRuntime:runtime,settingsManager,sessionManager,model,thinkingLevel:'high',tools:['reload_gate'],customTools:[{name:'reload_gate',label:'gate',description:'offline active tool',parameters:{type:'object',properties:{}},execute:async(_id,_args,signal)=>{toolSignal=signal;toolEntered();await gate;assert.equal(signal.aborted,false);return{content:[{type:'text',text:'RELOAD_TOOL_RESULT_RETAINED'}],details:{}};}}]}));
 session.agent.streamFunction=(m)=>{
  mainCalls++;
  const first=mainCalls===1;
  assert.ok(mainCalls<=2,'no unsolicited continuation');
  const out=new AssistantMessageEventStream();
  const message={role:'assistant',api:m.api,provider:m.provider,model:m.id,timestamp:Date.now(),stopReason:first?'toolUse':'stop',content:first?[{type:'toolCall',id:'reload-tool',name:'reload_gate',arguments:{}}]:[{type:'text',text:'RELOAD_FINAL_RETAINED'}],usage:{input:5000,output:10,cacheRead:0,cacheWrite:0,totalTokens:5010,cost:{input:0,output:0,cacheRead:0,cacheWrite:0,total:0}}};
  queueMicrotask(()=>{out.push({type:'done',reason:message.stopReason,message});out.end(message);});return out;
 };
 await session.bindExtensions({mode:'rpc',uiContext:{setStatus:()=>{},notify:()=>{},setWidget:()=>{},setToolsExpanded:()=>{}},onError:e=>{throw Error(JSON.stringify(e));}});
 const beforeId=session.sessionId;
 const beforeFile=session.sessionFile;
 const work=session.prompt('Keep this active tool and task intact.');
 await entered;
 assert.equal(session.isStreaming,true);
 const oldEntries=sessionManager.getEntries().map(e=>e.id);
 activeConfig={...mod.readConfig(''),startTokens:800000};
 await session.reload();
 assert.equal(session.isStreaming,true,'reload must not stop active generation');
 assert.equal(toolSignal.aborted,false,'reload must not abort active tool');
 assert.equal(session.sessionId,beforeId);
 assert.equal(session.sessionFile,beforeFile);
 assert.deepEqual(sessionManager.getEntries().slice(0,oldEntries.length).map(e=>e.id),oldEntries);
 assert.equal(logs.filter(e=>e.event==='loaded').at(-1).startTokens,800000);
 assert.equal(logs.filter(e=>e.event==='loaded').at(-1).firstToolCompaction,undefined);
 releaseTool();await work;
 assert.equal(mainCalls,2);
 assert.equal(summaries,0);
 assert.equal(session.thinkingLevel,'high');
 assert.deepEqual(settingsManager.getCompactionSettings(),native);
 const text=JSON.stringify(sessionManager.buildSessionContext().messages);
 assert.ok(text.includes('RELOAD_TOOL_RESULT_RETAINED'));
 assert.ok(text.includes('RELOAD_FINAL_RETAINED'));
 assert.equal(sessionManager.getEntries().filter(e=>e.type==='compaction').length,0);
 console.log('PASS: actual SDK reload while tool is running; active tool/model un-aborted; session ID/file/history/tail/thinking/native settings retained; loaded single startTokens=800000; network/model requests=0');
} finally {releaseTool?.();session?.dispose();globalThis.fetch=originalFetch;fs.rmSync(temp,{recursive:true,force:true});}
