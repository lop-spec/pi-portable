import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { resolveThoriumExecutable, dailyThoriumArgs, dailyThoriumProfile, persistentExtensionPaths } from "../src/thorium-browser.mjs";
import { resolveBrowserExecutable, BrowserRuntime } from "../src/browser-agent/runtime.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const env = { USERPROFILE: "C:/Users/test", LOCALAPPDATA: "C:/Users/test/AppData/Local", PI_PORTABLE_DATA: "D:/portable/data" };
const expected = path.join(env.PI_PORTABLE_DATA, "AppData", "Local", "Thorium", "Application", "thorium.exe");
assert.equal(resolveThoriumExecutable({ env, exists: (p) => p === expected }), expected);
assert.equal(resolveThoriumExecutable({ env, exists: () => false }), null);
const args = dailyThoriumArgs({ userHome: env.USERPROFILE, exists: (p) => p.endsWith(path.join("auto-close-old-tabs", "manifest.json")), persistent: new Set() });
assert(args.includes("--silent-debugger-extension-api"));
assert(!args.some((arg) => arg.startsWith("--remote-debugging-")));
assert(!args.some((arg) => arg.startsWith("--user-data-dir=")));
assert.equal(dailyThoriumProfile(), path.join(os.userInfo().homedir, "AppData", "Local", "Thorium", "User Data"));
assert(args.some((p) => p.startsWith("--load-extension=") && p.endsWith("auto-close-old-tabs")));
// A persistently installed extension must not be re-passed via --load-extension (it would become command-line only).
const persistentDir = path.resolve(path.join(env.USERPROFILE, "AppData", "Local", "Thorium", "Extensions", "auto-close-old-tabs")).toLowerCase();
const persistentArgs = dailyThoriumArgs({ userHome: env.USERPROFILE, exists: () => true, persistent: new Set([persistentDir]) });
assert(!persistentArgs.some((p) => p.includes("auto-close-old-tabs")));
assert(persistentArgs.some((p) => p.startsWith("--load-extension=") && p.endsWith("authenticator")));
const prefs = JSON.stringify({ extensions: { settings: { a: { location: 4, path: "C:\\Users\\test\\AppData\\Local\\Thorium\\Extensions\\auto-close-old-tabs" }, b: { location: 8, path: "C:\\Users\\test\\AppData\\Local\\Thorium\\Extensions\\authenticator" } } } });
assert.deepEqual([...persistentExtensionPaths({ userHome: env.USERPROFILE, readFile: () => prefs })], [persistentDir]);
const warnings = [];
assert.equal(persistentExtensionPaths({ userHome: env.USERPROFILE, readFile: () => { throw new Error("ENOENT"); }, log: text => warnings.push(text) }), null);
assert.match(warnings[0], /omitting --load-extension.*ENOENT/);
assert(!dailyThoriumArgs({ userHome: env.USERPROFILE, exists: () => true, persistent: null }).some(arg => arg.startsWith("--load-extension=")));
const runtime = new BrowserRuntime({ dataRoot: "D:/portable/data" });
assert.equal(runtime.profileDir, dailyThoriumProfile());
assert.equal(runtime.launchBrowser, false);
assert.equal(runtime.status().mode, "daily-attach");
assert.throws(() => new BrowserRuntime({ dataRoot: "D:/portable/data", launchBrowser: true }), /Refusing to launch/);
const source = fs.readFileSync(path.join(root, "src", "launcher.mjs"), "utf8");
const shared = source.slice(source.indexOf('if (path.basename(cmd[0]).toLowerCase() === "thorium.exe")'), source.indexOf("// --user-data-dir 独立配置"));
assert(shared.includes("dailyThoriumArgs()"));
// Cold start from Pi must carry the same port as the shortcuts/https association.
assert(shared.includes('"--remote-debugging-port=9222"'));
assert(shared.includes("detached: true"));
assert(!shared.includes("children.push("));
assert(!shared.includes("ledgerRecord("));
assert(!shared.includes("shutdown("));
const description = fs.readFileSync(path.join(root, "src", "browser-agent", "index.ts"), "utf8");
assert(description.includes("daily Thorium"));
assert(description.includes("Never connect to native remote-debugging ports"));
assert(description.includes('pi.on("session_shutdown", async () => { await runtime.detach();'));
const live = resolveThoriumExecutable();
if (live) assert.equal(await resolveBrowserExecutable(), live);
console.log("PASS Thorium discovery/daily-extension/attach-only/user-owned-process contracts");
