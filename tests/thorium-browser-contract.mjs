import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { resolveThoriumExecutable, dailyThoriumArgs } from "../src/thorium-browser.mjs";
import { resolveBrowserExecutable, BrowserRuntime } from "../src/browser-agent/runtime.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const env = { USERPROFILE: "C:/Users/test", LOCALAPPDATA: "C:/Users/test/AppData/Local", PI_PORTABLE_DATA: "D:/portable/data" };
const expected = path.join(env.PI_PORTABLE_DATA, "AppData", "Local", "Thorium", "Application", "thorium.exe");
assert.equal(resolveThoriumExecutable({ env, exists: (p) => p === expected }), expected);
assert.equal(resolveThoriumExecutable({ env, exists: () => false }), null);
const args = dailyThoriumArgs({ userHome: env.USERPROFILE, exists: (p) => p.endsWith(path.join("auto-close-old-tabs", "manifest.json")) });
assert(args.includes("--remote-debugging-address=127.0.0.1"));
assert(args.includes("--remote-debugging-port=9222"));
assert(args.includes(`--user-data-dir=${path.join(env.USERPROFILE, "AppData", "Local", "Thorium", "Daily User Data")}`));
assert(dailyThoriumArgs().includes(`--user-data-dir=${path.join(os.userInfo().homedir, "AppData", "Local", "Thorium", "Daily User Data")}`));
assert(args.some((p) => p.startsWith("--load-extension=") && p.endsWith("auto-close-old-tabs")));
const runtime = new BrowserRuntime({ dataRoot: "D:/portable/data" });
assert.equal(runtime.profileDir, path.join("D:/portable/data", "browser-agent", "profile"));
assert(!runtime.profileDir.includes("Daily User Data"));
const source = fs.readFileSync(path.join(root, "src", "launcher.mjs"), "utf8");
const shared = source.slice(source.indexOf('if (path.basename(cmd[0]).toLowerCase() === "thorium.exe")'), source.indexOf("// --user-data-dir 独立配置"));
assert(shared.includes("dailyThoriumArgs()"));
assert(shared.includes("detached: true"));
assert(!shared.includes("children.push("));
assert(!shared.includes("ledgerRecord("));
assert(!shared.includes("shutdown("));
const description = fs.readFileSync(path.join(root, "src", "browser-agent", "index.ts"), "utf8");
assert(description.includes("never connects to the user's daily browser profile"));
assert(description.includes("headless Thorium"));
const live = resolveThoriumExecutable();
if (live) assert.equal(await resolveBrowserExecutable(), live);
console.log("PASS Thorium discovery/daily-CDP/isolation/user-owned-process contracts");
