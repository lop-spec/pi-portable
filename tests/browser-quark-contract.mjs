import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {readDailyBrowserSelection,resolveDailyBrowserExecutable,queryQuarkAppPath,resolveDailyPlaywrightModule} from '../src/browser-agent/daily-browser.mjs';
import {ExtensionBrowserRuntime} from '../src/browser-agent/extension-runtime.mjs';
import {planBackgroundInstall,applyBackgroundInstall} from '../tools/install-background-browser.mjs';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'pi-quark-contract-'));
try {
  const dataRoot=path.join(temp,'data'),userHome=path.join(temp,'user'),agent=path.join(dataRoot,'browser-agent');
  fs.mkdirSync(agent,{recursive:true});
  const configFile=path.join(agent,'browser-config.json');
  assert.equal(readDailyBrowserSelection({dataRoot,userHome}).id,'thorium');
  const choice={browser:'quark',preserve:'unrelated-state'};
  fs.writeFileSync(configFile,JSON.stringify(choice));
  const selection=readDailyBrowserSelection({dataRoot,userHome});
  assert.equal(selection.name,'Quark');assert.equal(selection.profileDir,path.join(userHome,'AppData/Local/Quark/User Data'));
  const runtime=new ExtensionBrowserRuntime({dataRoot});
  assert.equal(runtime.status().mode,'quark-background-extension');assert.equal(runtime.status().browser,'Quark');
  assert.match((await runtime.execute({action:'close'})).content[0].text,/Quark/);
  let resolved=false;
  await assert.rejects(resolveDailyPlaywrightModule({playwrightModule:path.join(temp,'missing.mjs')},()=>{resolved=true;}),/refusing version fallback/);
  assert.equal(resolved,false);
  const executable='D:\\Program Files\\Quark\\quark.exe';
  const registryCalls=[];
  assert.equal(queryQuarkAppPath({platform:'win32',run:(cmd,args,options)=>{registryCalls.push({cmd,args,options});return {status:0,stdout:' (Default) REG_SZ '+executable+'\r\n'};}}),executable);
  assert.equal(registryCalls[0].options.windowsHide,true);assert.equal(registryCalls[0].options.shell,false);
  assert.equal(resolveDailyBrowserExecutable(selection,{queryAppPath:()=>executable,exists:p=>p===executable}),executable);
  assert.equal(resolveDailyBrowserExecutable(selection,{queryAppPath:()=>null,exists:p=>p.includes('Thorium')}),null,'Quark missing must not fall back to installed Thorium');
  assert.throws(()=>queryQuarkAppPath({platform:'win32',run:()=>({error:new Error('timeout')})}),/lookup failed/);
  fs.writeFileSync(configFile,'{"browser":"edge"}');assert.throws(()=>readDailyBrowserSelection({dataRoot}),/must be thorium or quark/);
  fs.writeFileSync(configFile,'{');assert.throws(()=>readDailyBrowserSelection({dataRoot}),/Invalid machine-local/);
  fs.writeFileSync(configFile,JSON.stringify(choice));
  const plan=planBackgroundInstall({browser:'quark',dataRoot,userHome});
  applyBackgroundInstall(plan);
  assert.equal(JSON.parse(fs.readFileSync(configFile,'utf8')).preserve,'unrelated-state');
  const second=planBackgroundInstall({browser:'quark',dataRoot,userHome});
  assert.equal(second.changes.length,0,'Rerun must not modify assets or rotate pairing');assert.equal(second.token,plan.token);
  const other=planBackgroundInstall({browser:'quark',dataRoot:path.join(temp,'other-data'),userHome:path.join(temp,'other-user')});
  assert.notEqual(other.token,plan.token,'Independent installations must never share generated pairing');
  fs.writeFileSync(plan.pairingFile,JSON.stringify({token:'x'.repeat(43)}));
  assert.throws(()=>planBackgroundInstall({browser:'quark',dataRoot,userHome}),/pairing mismatch/);
  console.log('PASS Quark selection/registry discovery/hidden queries/no fallback, local independent pairing, idempotent install/readback and unrelated-state retention');
}finally{fs.rmSync(temp,{recursive:true,force:true});}
